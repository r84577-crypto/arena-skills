# Office 2016 is the oldest build in the lab; the majority is newer but the exact
# version is unconfirmed, so every version-sensitive step gets its 2016 wording.
OFFICE = None


def office_note(key):
    """Version-specific fallback text, appended to the notes of the slide whose
    menu path is the one that changed between Office 2016 and later versions."""
    if key not in ("visual", "steps", "demo", "zoom"):
        return ""
    if key == "visual":
        return ("\n【Office 2016】أقدم إصدار في المعمل هو 2016: تبويب «تخطيط الصفحة» "
                "(Page Layout) هو الذي يحمل الهوامش وحجم الصفحة والاتجاه، أما في "
                "الإصدارات الأحدث فاسمه «تخطيط» (Layout). الأزرار نفسها في الموضع نفسه.")
    if key == "steps":
        return ("\n【Office 2016】إن لم تجد الأداة في المكان المذكور، فابحث عنها في "
                "تبويب «تخطيط الصفحة» (Page Layout) — الفرق بين 2016 والأحدث هو اسم "
                "التبويب غالبًا، وليس الإجراء. جرّب مرة واحدة قبل اللقاء على جهاز المعمل.")
    if key == "demo":
        return ("\n【قبل العرض】افتح الأداة على جهاز العرض نفسه، ولا تفترض أنها في "
                "الموضع نفسه في كل إصدار؛ أجهزة المعمل تتراوح بين 2016 وأحدث.")
    return ("\n【تنبيه إصدارات】أجهزة المعمل ليست متطابقة: أقدمها Office 2016 وأغلبها "
            "أحدث. حين يختلف اسم تبويب، اطلب من المتدرب وصف الأيقونة لا الاسم.")


def _join(items, bullet="• "):
    return "\n".join(bullet + str(i) for i in items)


